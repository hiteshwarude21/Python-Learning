name = "Hitesh"

print(len(name)) # This will print the length of the string "Hitesh"

print(name.upper()) # This will print the string "Hitesh" in uppercase
print(name.lower()) # This will print the string "Hitesh" in lowercase
print(name.capitalize()) # This will print the string "Hitesh" with the first letter capitalized
print(name.title()) # This will print the string "Hitesh" with each word capitalized